# arithmetic.py
def arithmetic_test():
    # Правильный ответ
    правильный_ответ = 4 * 100 - 54
    
    # Запрашиваем ответ у пользователя
    ответ_пользователя = input("Решите пример: 4 * 100 - 54 = ")
    
    # Преобразуем ввод пользователя в число
    # ДА, нужно преобразовать строку в число, чтобы сравнить с правильным ответом
    try:
        ответ_пользователя = int(ответ_пользователя)
    except ValueError:
        print("Пожалуйста, введите корректное число!")
        return
    
    # Выводим результаты
    print(f"Правильный ответ: {правильный_ответ}")
    print(f"Твой ответ: {ответ_пользователя}")

# Вызываем функцию
if __name__ == "__main__":
    arithmetic_test()
