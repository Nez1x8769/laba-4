# numbers.py
def calculate_numbers():
    # Запрашиваем четыре числа у пользователя
    try:
        число1 = float(input("Введите первое число: "))
        число2 = float(input("Введите второе число: "))
        число3 = float(input("Введите третье число: "))
        число4 = float(input("Введите четвертое число: "))
    except ValueError:
        print("Пожалуйста, введите корректные числа!")
        return
    
    # Складываем первые два и вторые два числа
    сумма_первых_двух = число1 + число2
    сумма_вторых_двух = число3 + число4
    
    # Проверяем деление на ноль
    if сумма_вторых_двух == 0:
        print("Ошибка: Деление на ноль! Сумма вторых двух чисел равна нулю.")
        return
    
    # Делим первую сумму на вторую
    результат = сумма_первых_двух / сумма_вторых_двух
    
    # Выводим результат с двумя цифрами после запятой
    print(f"Результат: {результат:.2f}")

# Вызываем функцию
if __name__ == "__main__":
    calculate_numbers()
