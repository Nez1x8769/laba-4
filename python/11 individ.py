# Вводим два числа
число1 = float(input("Введите первое число: "))
число2 = float(input("Введите второе число: "))

# Вычисляем модули
модуль1 = abs(число1)
модуль2 = abs(число2)

# Вычисляем средние значения
среднее_арифметическое = (модуль1 + модуль2) / 2
среднее_геометрическое = (модуль1 * модуль2) ** 0.5

# Выводим результаты с округлением
print(f"\nРезультаты:")
print(f"Среднее арифметическое модулей: {среднее_арифметическое:.2f}")
print(f"Среднее геометрическое модулей: {среднее_геометрическое:.2f}")
