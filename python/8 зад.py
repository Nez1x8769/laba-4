# user.py
def user_info():
    # Запрашиваем информацию у пользователя
    имя = input("Как тебя зовут? ")
    возраст = input("Сколько тебе лет? ")
    место_жительства = input("Где ты живешь? ")
    
    # Выводим информацию (ИСПРАВЛЕНО: используем переменную 'возраст')
    print(f"Это {имя}")
    print(f"Ему {возраст} лет")
    print(f"Он живет в {место_жительства}")

# Вызываем функцию
if __name__ == "__main__":
    user_info()
